print("OPERADORES ARITMÉTICOS DEL AEROPUERTO")
print("+ Suma: ", 10, "+", 5, "=", 10 + 5)
print("- Resta: ", 20, "-", 7, "=", 20 - 7)
print("* Multiplicación: ", 4, "*", 3, "=", 4 * 3)
print("/ División: ", 15, "/", 4, "=", 15 / 4)
print("// División entera: ", 15, "//", 4, "=", 15 // 4)
print("% Residuo: ", 10, "%", 3, "=", 10 % 3)
print("** Potencia: ", 2, "**", 3, "=", 2 ** 3)

print("Horas de espera en el aeropuerto")
print(2, "*", 3, "=", 2 * 3)
print(3, "*", 4, "=", 3 * 4)
print(5, "*", 2, "=", 5 * 2)

print("OPERADORES DE COMPARACIÓN")
print("== Igual a: ", 8, "==", 8, 8 == 8)
print("!= Diferente de: ", 8, "!=", 5, 8 != 5)
print("> Mayor que: ", 10, ">", 6, 10 > 6)
print("< Menor que: ", 5, "<", 9, 5 < 9)
print(">= Mayor o igual que: ", 12, ">=", 12, 12 >= 12)
print("<= Menor o igual que: ", 7, "<=", 10, 7 <= 10)

print("OPERADORES LÓGICOS")
print("and: (6 == 6) and (3 < 5)", (6 == 6) and (3 < 5))
print("and: (5 == 5) and (8 < 2)", (5 == 5) and (8 < 2))
print("or: (5 == 5) or (4 > 9)", (5 == 5) or (4 > 9))
print("not: not (7 == 9)", not (7 == 9))
